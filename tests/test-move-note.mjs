import assert from 'node:assert/strict';
import {detectNoteGroups,groupAtTime,groupForNote,GROUP_COLORS} from '../js/grouping.js';
import {withOpenF} from '../js/constants.js';
const marks=detectNoteGroups([0,210,450,700,1500,1720,1940,2170,3190,3440,3680,3920].map(time=>({time})));
assert.deepEqual(marks.map(m=>m.start),[0,1500,3190]);
const note={time:700,noteNumber:4,groupStart:undefined};
const neighbor={time:450};
assert.equal(groupForNote(marks,note),0);
assert.equal(groupForNote(marks,neighbor),0);
note.groupStart=marks[1].start;
assert.equal(groupForNote(marks,note),1,'move note only');
assert.equal(groupForNote(marks,neighbor),0,'neighbor remains in original group');
assert.equal(groupAtTime(marks,note.time),0,'recorded time remains unchanged');
assert.equal(marks[groupForNote(marks,note)].color,GROUP_COLORS[1],'inherits destination color');
const notes=withOpenF([{string:1,noteNumber:4,time:700,groupStart:marks[1].start}]);
assert.equal(notes.find(n=>n.noteNumber===14).groupStart,marks[1].start,'F companion inherits group color');
assert.equal(groupForNote(marks,{time:700,groupStart:999999}),0,'missing group falls back to time');
assert.equal(groupForNote(marks,{time:700}),0,'old saved songs still work');
console.log('OK: lëvizja individuale e notës ruan kohën, F dhe ngjyrën e grupit.');
