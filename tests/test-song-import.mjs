import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
const uploaded=JSON.parse(await fs.readFile(new URL('../songs/shtat-shaljan.json',import.meta.url),'utf8'));
for(const dir of ['../js/','../js/v26/']){
  const {importSongJSON,validateAudioFile}=await import(new URL(dir+'song-import.js',import.meta.url));
  const {upsertSong}=await import(new URL(dir+'songs.js',import.meta.url));
  const catalog={...uploaded,notes:uploaded.notes.slice(0,3)};
  const input=JSON.stringify(uploaded);
  const updated=importSongJSON(input,[catalog]);
  assert.equal(updated.existing,true);assert.equal(updated.song.id,catalog.id);
  assert.equal(updated.song.originalAudioId,catalog.originalAudioId);
  assert.equal(updated.song.notes.length,171);assert.equal(updated.song.stanzas.length,22);
  assert.deepEqual(updated.song.notes,uploaded.notes);
  const local={...catalog,originalAudioId:'local:'+catalog.id,originalAudioName:'Melodia ime.mp3'};
  const localUpdate=importSongJSON(input,[local]).song;
  assert.equal(localUpdate.originalAudioId,local.originalAudioId);
  assert.equal(localUpdate.originalAudioName,local.originalAudioName);
  assert.equal(upsertSong([local],localUpdate).length,1);
  const omitted={...uploaded};delete omitted.originalAudioId;
  assert.equal(importSongJSON(JSON.stringify(omitted),[local]).song.originalAudioId,local.originalAudioId);
  const fresh=importSongJSON(input,[]);
  assert.equal(fresh.existing,false);assert.equal(fresh.song.id,uploaded.id);
  assert.equal(fresh.song.originalAudioId,uploaded.originalAudioId);
  const bare={name:'Pa MP3',notes:[{time:0,string:1,noteNumber:3,withF:false,upperNoteNumber:7}]};
  const bareImported=importSongJSON(JSON.stringify(bare),[]).song;
  assert.ok(bareImported.id);assert.equal(bareImported.originalAudioId,undefined);
  assert.equal(bareImported.notes[0].withF,false);assert.equal(bareImported.notes[0].upperNoteNumber,7);
  const pending={...bare,originalAudioId:'__draft'};
  assert.equal(importSongJSON(JSON.stringify(pending),[]).song.originalAudioId,undefined);
  assert.throws(()=>importSongJSON('{broken',[]));
  assert.throws(()=>importSongJSON(JSON.stringify({...bare,id:4}),[]));
  assert.throws(()=>importSongJSON(JSON.stringify({...bare,notes:[{time:-1,string:1,noteNumber:5}]}),[]));
  validateAudioFile({name:'kënga.mp3',type:'',size:1577949});
  validateAudioFile({name:'recording',type:'audio/mpeg',size:100});
  assert.throws(()=>validateAudioFile({name:'empty.mp3',type:'audio/mpeg',size:0}));
  assert.throws(()=>validateAudioFile({name:'big.mp3',type:'audio/mpeg',size:25_000_001}));
  assert.throws(()=>validateAudioFile({name:'notes.json',type:'application/json',size:100}));
  assert.deepEqual(catalog.notes,uploaded.notes.slice(0,3));
  console.log(`OK ${dir}: imported JSON preserves MP3 identity, local attachment, updated notes/groups and validation`);
}
